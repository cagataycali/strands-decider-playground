"""Generate the model table in .github/README.md.

Facts are read, not typed: names + JevBench correct/231 + Brier + p50 ms come from
bench/baseline/meta.json (captured on the Space); base model + LoRA rank come from each
repo's decider config on the Hub (the same file registry.py reads). Nothing is loaded.

    python docs/gen_readme_table.py            # rewrites the table between the markers
    python docs/gen_readme_table.py --check    # exit 1 if the README is stale
"""
from __future__ import annotations

import json
import os
import re
import sys

from huggingface_hub import hf_hub_download

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
META = os.path.join(ROOT, "bench", "baseline", "meta.json")
README = os.path.join(ROOT, ".github", "README.md")
ORG = os.environ.get("DECIDER_ORG", "StrandsAgents")
CONFIG_NAMES = ("strands_decider_config.json", "hobson_config.json")
START, END = "<!-- models:start -->", "<!-- models:end -->"


def config(repo: str) -> dict:
    """The decider config of one repo, from the Hub (public repos; no token needed)."""
    for name in CONFIG_NAMES:
        try:
            with open(hf_hub_download(repo, name, token=os.environ.get("HF_TOKEN") or None)) as f:
                return json.load(f)
        except Exception:  # noqa: BLE001 -- try the next known config name
            continue
    return {}


def table() -> str:
    meta = json.load(open(META))
    rows = []
    for name in meta["models"]:
        pm = meta["per_model"][name]
        cfg = config(f"{ORG}/{name}")
        base = (cfg.get("base_model") or "?").split("/")[-1]
        r = cfg.get("lora_r") or cfg.get("r") or "–"
        rows.append((pm["correct"], name, base, r, pm["brier"], pm["p50_ms"], pm["n"]))
    rows.sort(key=lambda t: -t[0])
    out = ["| model | base | LoRA r | JevBench | Brier | p50 |", "|---|---|---:|---:|---:|---:|"]
    for correct, name, base, r, brier, p50, n in rows:
        out.append(f"| [{name}](https://huggingface.co/{ORG}/{name}) | {base} | {r} | {correct}/{n} | {brier:.3f} | {p50:.0f} ms |")
    out.append("")
    out.append(f"<sub>Generated by `docs/gen_readme_table.py` from `bench/baseline/meta.json` — "
               f"{meta['n_cells']} cells captured {meta['captured_utc']} on {meta['hardware_detail']}; "
               f"p50 is the forward pass alone. Base and rank are read from each repo's decider config.</sub>")
    return "\n".join(out)


def main() -> int:
    text = open(README).read()
    new = table()
    pat = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pat.search(text):
        sys.exit(f"{README}: markers {START} … {END} not found")
    updated = pat.sub(f"{START}\n{new}\n{END}", text)
    if "--check" in sys.argv:
        if updated != text:
            print("model table is stale: run docs/gen_readme_table.py"); return 1
        print("model table up to date"); return 0
    open(README, "w").write(updated)
    print(new)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
